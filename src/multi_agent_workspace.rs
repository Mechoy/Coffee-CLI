/// Process-local state. It is intentionally never persisted: a new Coffee
/// process must use new tab/session/run identities and acquire a fresh restore
/// lease before it can start a prior workspace again.
#[derive(Default)]
pub struct WorkspaceRuntime {
    attempts: HashMap<String, RestoreAttempt>,
    snapshot_attempts: HashMap<String, String>,
    live_panes: HashMap<String, LivePaneBinding>,
    history_selections: HashMap<String, HistorySelection>,
    /// Snapshots created while a fresh pane is still in its pre-spawn window.
    /// A failed first launch must not leave a recovery card for a conversation
    /// that never existed. The first successful PTY spawn commits the snapshot.
    uncommitted_snapshots: HashSet<String>,
    /// Deduplicates short native-history confirmation retries for Coffee-owned
    /// Claude UUIDs. This is process-only bookkeeping, never recovery state.
    pending_claude_identity_checks: HashSet<String>,
    discarded_snapshots: VecDeque<String>,
    renderer_instance_id: Option<String>,
    shutting_down: bool,
}

