pub fn begin_restore(
    lock: &Arc<Mutex<()>>,
    runtime: &Arc<Mutex<WorkspaceRuntime>>,
    snapshot_id: &str,
    expected_revision: u64,
    renderer_instance_id: &str,
) -> Result<BeginRestoreResult, String> {
    validate_snapshot_id(snapshot_id)?;
    validate_renderer_instance_id(renderer_instance_id)?;
    let (snapshot, revision) = {
        let _guard = lock
            .lock()
            .map_err(|_| "Multi-agent workspace lock was poisoned".to_string())?;
        let store = load_store()?;
        if store.revision != expected_revision {
            return Err("This workspace changed; refresh its restore check before starting it".to_string());
        }
        let snapshot = store
            .workspaces
            .iter()
            .find(|snapshot| snapshot.snapshot_id == snapshot_id)
            .cloned()
            .ok_or_else(|| "Multi-agent workspace was not found".to_string())?;
        (snapshot, store.revision)
    };
    let plan = preflight_snapshot(&snapshot, revision);
    if !plan_is_ready(&plan) {
        return Err("One or more panes need attention before this workspace can be restored".to_string());
    }
    let attempt = computed_attempt(&snapshot, &plan)?;

    let _guard = lock
        .lock()
        .map_err(|_| "Multi-agent workspace lock was poisoned".to_string())?;
    let store = load_store()?;
    if store.revision != revision {
        return Err("This workspace changed while it was being checked; run restore again".to_string());
    }
    let mut runtime = runtime
        .lock()
        .map_err(|_| "Multi-agent workspace runtime lock was poisoned".to_string())?;
    prune_unclaimed_restore_attempts(&mut runtime);
    if runtime.shutting_down {
        return Err("Coffee CLI is shutting down; cannot restore a multi-agent workspace".to_string());
    }
    ensure_current_renderer(&runtime, renderer_instance_id)?;
    if runtime.snapshot_attempts.contains_key(snapshot_id) {
        return Err("This multi-agent workspace is already being restored in this Coffee session".to_string());
    }
    if runtime
        .live_panes
        .values()
        .any(|binding| binding.snapshot_id == snapshot_id)
    {
        return Err("This multi-agent workspace is already open in this Coffee session".to_string());
    }
    let attempt_id = Uuid::new_v4().to_string();
    runtime.snapshot_attempts.insert(snapshot_id.to_string(), attempt_id.clone());
    runtime.attempts.insert(attempt_id.clone(), attempt);
    Ok(BeginRestoreResult { attempt_id, plan })
}

pub fn release_restore_attempt(
    runtime: &Arc<Mutex<WorkspaceRuntime>>,
    attempt_id: &str,
) -> Result<(), String> {
    let mut runtime = runtime
        .lock()
        .map_err(|_| "Multi-agent workspace runtime lock was poisoned".to_string())?;
    prune_unclaimed_restore_attempts(&mut runtime);
    if let Some(attempt) = runtime.attempts.get_mut(attempt_id) {
        // Closing the restored tab (or abandoning a post-begin UI transition)
        // must prevent delayed, unmounted panes from consuming this lease.
        // Existing PTYs retain their binding until their normal kill/exit
        // cleanup removes it, at which point release_idle_attempt deletes the
        // now fully settled attempt.
        attempt.pending_launch_panes.clear();
    }
    release_idle_attempt(&mut runtime, attempt_id);
    Ok(())
}

/// Settle a pane that failed before it could consume its restore permit.
/// This is deliberately idempotent: a backend spawn rollback may already
/// have removed a claimed pane by the time the WebView reports the failure.
pub fn cancel_restore_pane_launch(
    runtime: &Arc<Mutex<WorkspaceRuntime>>,
    session_id: &str,
    attempt_ref: &RestoreAttemptRef,
) -> Result<(), String> {
    validate_snapshot_id(&attempt_ref.snapshot_id)?;
    Uuid::parse_str(&attempt_ref.attempt_id)
        .map_err(|_| "Invalid multi-agent restore attempt".to_string())?;
    if attempt_ref.pane_index == 0 {
        return Err("Invalid multi-agent pane index".to_string());
    }
    let (_, session_pane) = parse_pane_session_id(session_id)?;
    if session_pane != attempt_ref.pane_index {
        return Err("Restore attempt pane does not match this terminal session".to_string());
    }
    let mut runtime = runtime
        .lock()
        .map_err(|_| "Multi-agent workspace runtime lock was poisoned".to_string())?;
    prune_unclaimed_restore_attempts(&mut runtime);
    if let Some(attempt) = runtime.attempts.get_mut(&attempt_ref.attempt_id) {
        if attempt.snapshot_id != attempt_ref.snapshot_id {
            return Err("Restore attempt does not own this multi-agent workspace".to_string());
        }
        if !attempt.panes.contains_key(&attempt_ref.pane_index) {
            return Err("Restore attempt does not own this multi-agent pane".to_string());
        }
        // Never modify `claimed_panes`: a live/claimed sibling or an already
        // spawned pane must remain valid. This only revokes a permit that was
        // still waiting to be consumed by a failed mount.
        attempt.pending_launch_panes.remove(&attempt_ref.pane_index);
    }
    release_idle_attempt(&mut runtime, &attempt_ref.attempt_id);
    Ok(())
}

/// A Tauri process can outlive a crashed or reloaded WebView. The first IPC
/// from a new renderer therefore retires every old coordinated pane before it
/// can block recovery or keep a hidden child process alive.
pub fn register_renderer_instance(
    lock: &Arc<Mutex<()>>,
    runtime: &Arc<Mutex<WorkspaceRuntime>>,
    terminal_sessions: &crate::terminal::SharedSession,
    terminal_launches: &crate::terminal::SharedLaunchRegistry,
    renderer_instance_id: &str,
) -> Result<Vec<(String, String)>, String> {
    validate_renderer_instance_id(renderer_instance_id)?;
    // Match every persistent mutation's lock order (`workspace -> runtime`).
    // This makes renderer replacement a linear boundary: an old renderer can
    // finish a write before this registration, or be rejected afterwards, but
    // cannot write across the ownership handoff.
    let _guard = lock
        .lock()
        .map_err(|_| "Multi-agent workspace lock was poisoned".to_string())?;
    // The PTY installation path holds this same workspace lock from its final
    // launch check through the provisional-to-durable transition. Sampling the
    // terminal map here therefore cannot race an install half-way through that
    // transition: every matching key is either genuinely installed or still
    // safe to discard as a failed pre-spawn launch.
    let installed_runs: HashSet<String> = terminal_sessions
        .lock()
        .map_err(|_| "Terminal session lock was poisoned".to_string())?
        .iter()
        .map(|(session_id, session)| pane_run_key(session_id, &session.run_id))
        .collect();
    let mut runtime = runtime
        .lock()
        .map_err(|_| "Multi-agent workspace runtime lock was poisoned".to_string())?;
    if runtime.shutting_down {
        return Err("Coffee CLI is shutting down; renderer registration is unavailable".to_string());
    }
    let replaced = runtime
        .renderer_instance_id
        .as_deref()
        .is_some_and(|current| current != renderer_instance_id);
    if !replaced {
        runtime.renderer_instance_id = Some(renderer_instance_id.to_string());
        return Ok(Vec::new());
    }

    let runs: Vec<_> = runtime
        .live_panes
        .keys()
        .filter_map(|key| key.split_once('\0').map(|(session, run)| (session.to_string(), run.to_string())))
        .collect();
    // Cancel reserved generations before releasing the workspace lock. A
    // blocking spawn cannot install a late old PTY after this handoff has
    // cleared its recovery binding.
    {
        let mut launches = terminal_launches
            .lock()
            .map_err(|_| "Terminal launch registry lock was poisoned".to_string())?;
        for (session_id, run_id) in &runs {
            launches.cancel(session_id, run_id);
        }
    }

    // A renderer replacement retires every old generation. A provisional
    // snapshot with an already installed PTY is a real conversation and must
    // be preserved; only records whose complete set of launches was still
    // pre-spawn are discarded.
    let installed_provisionals: HashSet<String> = runtime
        .live_panes
        .iter()
        .filter_map(|(key, binding)| {
            (installed_runs.contains(key)
                && runtime.uncommitted_snapshots.contains(&binding.snapshot_id))
                .then(|| binding.snapshot_id.clone())
        })
        .collect();
    let discarded_provisionals: HashSet<String> = runtime
        .uncommitted_snapshots
        .difference(&installed_provisionals)
        .cloned()
        .collect();
    if !discarded_provisionals.is_empty() {
        let mut store = load_store()?;
        let before = store.workspaces.len();
        store
            .workspaces
            .retain(|snapshot| !discarded_provisionals.contains(&snapshot.snapshot_id));
        if store.workspaces.len() != before {
            bump_revision(&mut store)?;
            save_store(&store)?;
        }
    }
    runtime.live_panes.clear();
    runtime.attempts.clear();
    runtime.snapshot_attempts.clear();
    runtime.history_selections.clear();
    runtime.uncommitted_snapshots.clear();
    runtime.pending_claude_identity_checks.clear();
    runtime.renderer_instance_id = Some(renderer_instance_id.to_string());
    Ok(runs)
}

pub fn prepare_terminal_launch(
    lock: &Arc<Mutex<()>>,
    runtime: &Arc<Mutex<WorkspaceRuntime>>,
    context: WorkspaceCheckpoint,
    attempt_ref: Option<&RestoreAttemptRef>,
    renderer_instance_id: &str,
    session_id: &str,
    run_id: &str,
    requested_tool: Option<&str>,
    requested_cwd: Option<&str>,
) -> Result<WorkspaceLaunchGrant, String> {
    let input = validate_checkpoint(context)?;
    validate_renderer_instance_id(renderer_instance_id)?;
    let (_tab_id, session_pane) = parse_pane_session_id(session_id)?;
    if session_pane == 0 || session_pane > input.pane_count {
        return Err("Terminal session pane does not match the workspace layout".to_string());
    }
    let request_tool = requested_tool
        .ok_or_else(|| "Multi-agent workspace launch requires a tool".to_string())
        .and_then(CoordinatedTool::parse)?;
    let requested_cwd = requested_cwd.ok_or_else(|| "Multi-agent workspace launch requires a workspace".to_string())?;
    if normalize_workspace(requested_cwd)? != input.workspace {
        return Err("Multi-agent pane launch directory does not match the saved workspace".to_string());
    }

    let _guard = lock
        .lock()
        .map_err(|_| "Multi-agent workspace lock was poisoned".to_string())?;
    // Fence the renderer before touching persistent state. Holding the runtime
    // guard until this launch has either been bound or rejected makes a
    // renderer handoff linear with the checkpoint it may create.
    let mut runtime = runtime
        .lock()
        .map_err(|_| "Multi-agent workspace runtime lock was poisoned".to_string())?;
    prune_unclaimed_restore_attempts(&mut runtime);
    if runtime.shutting_down {
        return Err("Coffee CLI is shutting down; cannot launch a multi-agent pane".to_string());
    }
    ensure_current_renderer(&runtime, renderer_instance_id)?;
    if runtime.discarded_snapshots.contains(&input.snapshot_id) {
        return Err("This multi-agent workspace was discarded".to_string());
    }
    let mut store = load_store()?;
    let previous = store
        .workspaces
        .iter()
        .find(|snapshot| snapshot.snapshot_id == input.snapshot_id)
        .cloned();
    let is_restore = attempt_ref.is_some();
    if is_restore {
        let snapshot = store
            .workspaces
            .iter()
            .find(|snapshot| snapshot.snapshot_id == input.snapshot_id)
            .ok_or_else(|| "This multi-agent workspace record no longer exists".to_string())?;
        if !checkpoint_matches_snapshot(snapshot, &input) {
            return Err("The restored workspace layout changed before its panes started".to_string());
        }
    } else if apply_checkpoint(&mut store, input.clone(), true)? {
        bump_revision(&mut store)?;
        save_store(&store)?;
        if previous.is_none() {
            runtime
                .uncommitted_snapshots
                .insert(input.snapshot_id.clone());
        }
    }

    let snapshot = store
        .workspaces
        .iter()
        .find(|snapshot| snapshot.snapshot_id == input.snapshot_id)
        .cloned()
        .ok_or_else(|| "Multi-agent workspace record was not found".to_string())?;
    let pane = snapshot
        .panes
        .iter()
        .find(|pane| pane.pane_index == session_pane)
        .ok_or_else(|| "Multi-agent pane was not found".to_string())?;
    if pane.tool != Some(request_tool) {
        return Err("Terminal tool does not match the saved multi-agent pane".to_string());
    }

    if !is_restore {
        reconcile_live_panes(&mut runtime, previous.as_ref(), &snapshot);
    }
    let current_session_prefix = format!("{session_id}\0");
    if runtime.live_panes.iter().any(|(key, binding)| {
        binding.snapshot_id == snapshot.snapshot_id
            && binding.pane_index == session_pane
            && !key.starts_with(&current_session_prefix)
    }) {
        return Err("This multi-agent pane is already owned by another live terminal".to_string());
    }
    let resume_token = if let Some(attempt_ref) = attempt_ref {
        if attempt_ref.snapshot_id != snapshot.snapshot_id || attempt_ref.pane_index != session_pane {
            return Err("Restore attempt does not own this multi-agent pane".to_string());
        }
        let attempt = runtime
            .attempts
            .get_mut(&attempt_ref.attempt_id)
            .ok_or_else(|| "Restore attempt is no longer active".to_string())?;
        if attempt.snapshot_id != snapshot.snapshot_id
            || attempt.checkpoint_version != snapshot.checkpoint_version
        {
            return Err("Restore attempt is stale; check the workspace again before starting it".to_string());
        }
        let planned = attempt
            .panes
            .get(&session_pane)
            .ok_or_else(|| "Restore attempt is missing this pane".to_string())?;
        if !matches!(planned.status, RestorePaneStatus::Resumable | RestorePaneStatus::Fresh) {
            return Err("This multi-agent pane was not approved for launch".to_string());
        }
        if !attempt.pending_launch_panes.contains(&session_pane) {
            return Err("This multi-agent pane has already been launched for the restore attempt".to_string());
        }
        let current_config = mcp_config::load();
        let current_mcp = resolve_mcp_fingerprint(
            current_config.as_ref().map_err(|error| error),
            &pane.mcp_selection,
            request_tool,
            &snapshot.workspace,
            session_pane,
        )?;
        if planned.mcp.as_ref() != Some(&current_mcp) {
            return Err("MCP configuration changed after preflight; check the workspace again before starting it".to_string());
        }
        let resume_token = match (planned.status, &pane.continuation) {
            (RestorePaneStatus::Resumable, PaneContinuation::Known { token, .. }) => Some(token.clone()),
            (RestorePaneStatus::Fresh, PaneContinuation::FreshByUser) => None,
            _ => return Err("This multi-agent pane continuation changed after preflight".to_string()),
        };
        // Consume exactly this pane's permit only after all validations pass.
        // A sibling pane can still use its own permit if this launch later
        // fails during PTY spawn or terminal initialization.
        if !attempt.pending_launch_panes.remove(&session_pane) {
            return Err("This multi-agent pane has already been launched for the restore attempt".to_string());
        }
        attempt.claimed_panes.insert(session_pane);
        resume_token
    } else {
        None
    };
    // Fresh Claude panes receive an identity that Coffee generated itself.
    // Resume launches deliberately carry only the verified prior token; never
    // combine `--resume` and `--session-id` in one Claude invocation.
    let generated_claude_session_id = (request_tool == CoordinatedTool::Claude && resume_token.is_none())
        .then(|| Uuid::new_v4().to_string());
    // A replacement terminal may still have an old reader draining output.
    // Remove its run binding before registering the new generation; terminal.rs
    // also checks the current run id, so both layers reject a stale token.
    let stale_keys: Vec<_> = runtime
        .live_panes
        .keys()
        .filter(|key| key.starts_with(&current_session_prefix))
        .cloned()
        .collect();
    for key in stale_keys {
        remove_live_pane_binding(&mut runtime, &key);
    }
    let key = pane_run_key(session_id, run_id);
    runtime.live_panes.insert(
        key,
        LivePaneBinding {
            snapshot_id: snapshot.snapshot_id.clone(),
            pane_index: session_pane,
            checkpoint_version: snapshot.checkpoint_version,
            tool: request_tool,
            attempt_id: attempt_ref.map(|value| value.attempt_id.clone()),
            expected_claude_session_id: generated_claude_session_id.clone(),
        },
    );
    Ok(WorkspaceLaunchGrant {
        resume_token,
        generated_claude_session_id,
    })
}

/// Mark a prepared fresh workspace as durable only after the PTY was actually
/// installed. Before that point the store record is provisional and can be
/// removed if every pre-spawn launch fails or is cancelled.
fn commit_terminal_launch_locked(
    runtime: &mut WorkspaceRuntime,
    session_id: &str,
    run_id: &str,
) {
    if let Some(snapshot_id) = runtime
        .live_panes
        .get(&pane_run_key(session_id, run_id))
        .map(|binding| binding.snapshot_id.clone())
    {
        runtime.uncommitted_snapshots.remove(&snapshot_id);
    }
}

/// Caller must hold `WorkspaceRuntime`'s workspace lock. This is used by the
/// PTY spawn path so renderer replacement cannot observe an installed child
/// before its topology leaves the provisional state.
pub(crate) fn commit_terminal_launch_while_workspace_locked(
    runtime: &Arc<Mutex<WorkspaceRuntime>>,
    session_id: &str,
    run_id: &str,
) -> Result<(), String> {
    let mut runtime = runtime
        .lock()
        .map_err(|_| "Multi-agent workspace runtime lock was poisoned".to_string())?;
    commit_terminal_launch_locked(&mut runtime, session_id, run_id);
    Ok(())
}

pub fn rollback_terminal_launch(
    lock: &Arc<Mutex<()>>,
    runtime: &Arc<Mutex<WorkspaceRuntime>>,
    session_id: &str,
    run_id: &str,
) {
    let Ok(_guard) = lock.lock() else {
        return;
    };
    let Ok(mut runtime) = runtime.lock() else {
        return;
    };
    let key = pane_run_key(session_id, run_id);
    let snapshot_id = runtime
        .live_panes
        .get(&key)
        .map(|binding| binding.snapshot_id.clone());
    remove_live_pane_binding(&mut runtime, &key);
    let Some(snapshot_id) = snapshot_id else {
        return;
    };
    if !runtime.uncommitted_snapshots.contains(&snapshot_id)
        || snapshot_has_runtime_ownership(&runtime, &snapshot_id)
    {
        return;
    }

    // No launch ever reached a live PTY for this newly-created snapshot. Drop
    // it instead of surfacing an empty recovery card after a failed startup.
    match load_store() {
        Ok(mut store) => {
            let before = store.workspaces.len();
            store.workspaces.retain(|snapshot| snapshot.snapshot_id != snapshot_id);
            if store.workspaces.len() != before {
                if let Err(error) = bump_revision(&mut store).and_then(|_| save_store(&store)) {
                    eprintln!("[multi-agent-workspace] failed to remove provisional snapshot: {error}");
                    return;
                }
            }
            runtime.uncommitted_snapshots.remove(&snapshot_id);
        }
        Err(error) => eprintln!("[multi-agent-workspace] failed to load provisional snapshot store: {error}"),
    }
}

pub fn release_terminal_run(
    lock: &Arc<Mutex<()>>,
    runtime: &Arc<Mutex<WorkspaceRuntime>>,
    session_id: &str,
    run_id: &str,
) {
    let Ok(_guard) = lock.lock() else {
        return;
    };
    let Ok(mut runtime) = runtime.lock() else {
        return;
    };
    remove_live_pane_binding(&mut runtime, &pane_run_key(session_id, run_id));
}

/// Claim a short native-history confirmation window for one Coffee-generated
/// Claude UUID. The caller never supplies a token, so terminal output cannot
/// forge or replace the recovery identity.
pub fn begin_managed_claude_identity_confirmation(
    runtime: &Arc<Mutex<WorkspaceRuntime>>,
    session_id: &str,
    run_id: &str,
) -> bool {
    let key = pane_run_key(session_id, run_id);
    let Ok(mut runtime) = runtime.lock() else {
        return false;
    };
    let is_managed_claude = runtime
        .live_panes
        .get(&key)
        .is_some_and(|binding| {
            binding.tool == CoordinatedTool::Claude
                && binding.expected_claude_session_id.is_some()
        });
    is_managed_claude && runtime.pending_claude_identity_checks.insert(key)
}

pub fn finish_managed_claude_identity_confirmation(
    runtime: &Arc<Mutex<WorkspaceRuntime>>,
    session_id: &str,
    run_id: &str,
) {
    if let Ok(mut runtime) = runtime.lock() {
        runtime
            .pending_claude_identity_checks
            .remove(&pane_run_key(session_id, run_id));
    }
}

/// Confirm the UUID that Coffee itself injected into a fresh Claude launch.
/// Unlike the legacy PTY-token path, this function accepts no externally
/// sourced identity: it reads the expected UUID from the exact live run, then
/// verifies the matching native Claude JSONL file in the same workspace.
pub fn confirm_generated_claude_identity(
    lock: &Arc<Mutex<()>>,
    runtime: &Arc<Mutex<WorkspaceRuntime>>,
    session_id: &str,
    run_id: &str,
) -> Result<bool, String> {
    let key = pane_run_key(session_id, run_id);
    let (binding, workspace, expected_session_id) = {
        let _guard = lock
            .lock()
            .map_err(|_| "Multi-agent workspace lock was poisoned".to_string())?;
        let runtime = runtime
            .lock()
            .map_err(|_| "Multi-agent workspace runtime lock was poisoned".to_string())?;
        let Some(binding) = runtime.live_panes.get(&key).cloned() else {
            return Ok(false);
        };
        if binding.tool != CoordinatedTool::Claude {
            return Ok(false);
        }
        let Some(expected_session_id) = binding.expected_claude_session_id.clone() else {
            return Ok(false);
        };
        let store = load_store()?;
        let Some(snapshot) = store
            .workspaces
            .iter()
            .find(|snapshot| snapshot.snapshot_id == binding.snapshot_id)
        else {
            return Ok(false);
        };
        if snapshot.checkpoint_version != binding.checkpoint_version {
            return Ok(false);
        }
        (binding, snapshot.workspace.clone(), expected_session_id)
    };

    if !crate::server::claude_history_has_exact_session(&workspace, &expected_session_id)? {
        return Ok(false);
    }

    let _guard = lock
        .lock()
        .map_err(|_| "Multi-agent workspace lock was poisoned".to_string())?;
    let runtime = runtime
        .lock()
        .map_err(|_| "Multi-agent workspace runtime lock was poisoned".to_string())?;
    let still_current = runtime
        .live_panes
        .get(&key)
        .is_some_and(|current| {
            current == &binding
                && current.expected_claude_session_id.as_deref()
                    == Some(expected_session_id.as_str())
        });
    if !still_current {
        return Ok(false);
    }
    let mut store = load_store()?;
    let snapshot = store
        .workspaces
        .iter_mut()
        .find(|snapshot| snapshot.snapshot_id == binding.snapshot_id)
        .ok_or_else(|| "Multi-agent workspace disappeared before Claude identity confirmation".to_string())?;
    if snapshot.checkpoint_version != binding.checkpoint_version {
        return Ok(false);
    }
    let pane = snapshot
        .panes
        .iter_mut()
        .find(|pane| pane.pane_index == binding.pane_index)
        .ok_or_else(|| "Multi-agent pane disappeared before Claude identity confirmation".to_string())?;
    if pane.tool != Some(CoordinatedTool::Claude) {
        return Ok(false);
    }
    if matches!(pane.continuation, PaneContinuation::Skipped) {
        return Ok(false);
    }
    if matches!(
        &pane.continuation,
        PaneContinuation::Known {
            token: existing,
            source: ContinuationSource::ManagedClaudeSession,
            ..
        } if existing == &expected_session_id
    ) {
        return Ok(true);
    }
    pane.continuation = PaneContinuation::Known {
        token: expected_session_id,
        source: ContinuationSource::ManagedClaudeSession,
        observed_at: now_millis(),
    };
    snapshot.updated_at = now_millis();
    bump_revision(&mut store)?;
    save_store(&store)?;
    Ok(true)
}

/// Cancel every outstanding restore identity before application shutdown.
/// The caller feeds the returned generations into TerminalLaunchRegistry so a
/// reserved-but-not-yet-installed PTY cannot become an orphan after exit.
pub fn cancel_all_for_shutdown(
    lock: &Arc<Mutex<()>>,
    runtime: &Arc<Mutex<WorkspaceRuntime>>,
    terminal_sessions: &crate::terminal::SharedSession,
    terminal_launches: &crate::terminal::SharedLaunchRegistry,
) -> Result<Vec<(String, String)>, String> {
    let _guard = lock
        .lock()
        .map_err(|_| "Multi-agent workspace lock was poisoned".to_string())?;
    let installed_runs: HashSet<String> = terminal_sessions
        .lock()
        .map_err(|_| "Terminal session lock was poisoned".to_string())?
        .iter()
        .map(|(session_id, session)| pane_run_key(session_id, &session.run_id))
        .collect();
    let mut runtime = runtime
        .lock()
        .map_err(|_| "Multi-agent workspace runtime lock was poisoned".to_string())?;
    let ids = runtime
        .live_panes
        .keys()
        .filter_map(|key| key.split_once('\0').map(|(session, run)| (session.to_string(), run.to_string())))
        .collect::<Vec<_>>();
    {
        let mut launches = terminal_launches
            .lock()
            .map_err(|_| "Terminal launch registry lock was poisoned".to_string())?;
        for (session_id, run_id) in &ids {
            launches.cancel(session_id, run_id);
        }
    }

    let installed_provisionals: HashSet<String> = runtime
        .live_panes
        .iter()
        .filter_map(|(key, binding)| {
            (installed_runs.contains(key)
                && runtime.uncommitted_snapshots.contains(&binding.snapshot_id))
                .then(|| binding.snapshot_id.clone())
        })
        .collect();
    let discarded_provisionals: HashSet<String> = runtime
        .uncommitted_snapshots
        .difference(&installed_provisionals)
        .cloned()
        .collect();
    if !discarded_provisionals.is_empty() {
        let mut store = load_store()?;
        let before = store.workspaces.len();
        store
            .workspaces
            .retain(|snapshot| !discarded_provisionals.contains(&snapshot.snapshot_id));
        if store.workspaces.len() != before {
            bump_revision(&mut store)?;
            save_store(&store)?;
        }
    }
    runtime.shutting_down = true;
    runtime.live_panes.clear();
    runtime.attempts.clear();
    runtime.snapshot_attempts.clear();
    runtime.history_selections.clear();
    runtime.uncommitted_snapshots.clear();
    runtime.pending_claude_identity_checks.clear();
    Ok(ids)
}

