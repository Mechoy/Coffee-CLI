//! Persistent recovery metadata for coordinated multi-agent workspaces.
//!
//! Native CLIs own their conversation history. Coffee only stores the small
//! amount of topology needed to rebuild a 2/3/4-pane workspace and reconnect
//! it to a *verified* native resume identity. PTYs, output, task queues, MCP
//! endpoints, temporary paths, and secrets are deliberately excluded.

use crate::mcp_config::{self, McpConfig, McpProfileSelection};
use serde::{Deserialize, Serialize};
use std::{
    collections::{BTreeMap, HashMap, HashSet, VecDeque},
    fs,
    io::Write,
    path::{Path, PathBuf},
    sync::{Arc, Mutex},
    time::{Duration, SystemTime, UNIX_EPOCH},
};
use uuid::Uuid;

const STORE_VERSION: u32 = 1;
const MAX_WORKSPACES: usize = 32;
const MAX_STORE_BYTES: u64 = 1024 * 1024;
const MAX_SNAPSHOT_BYTES: usize = 64 * 1024;
const MAX_PATH_BYTES: usize = 4096;
const MAX_REASON_BYTES: usize = 512;
const MAX_DISCARDED_TOMBSTONES: usize = 64;
const MAX_HISTORY_SELECTIONS: usize = 256;
const HISTORY_SELECTION_TTL: Duration = Duration::from_secs(10 * 60);
const UNCLAIMED_RESTORE_ATTEMPT_TTL: Duration = Duration::from_secs(2 * 60);
const MAX_ORPHAN_FILES_PER_PASS: usize = 32;
const ORPHAN_MIN_AGE: Duration = Duration::from_secs(5 * 60);
const STORE_ORPHAN_PREFIX: &str = ".multi-agent-workspaces.";

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum CoordinatedTool {
    Claude,
    Codex,
    Opencode,
}

impl CoordinatedTool {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Claude => "claude",
            Self::Codex => "codex",
            Self::Opencode => "opencode",
        }
    }

    fn parse(value: &str) -> Result<Self, String> {
        match value {
            "claude" => Ok(Self::Claude),
            "codex" => Ok(Self::Codex),
            "opencode" => Ok(Self::Opencode),
            _ => Err(format!("'{value}' is not a coordinated multi-agent tool")),
        }
    }
}

